/**
 * 该轮是否注入格式指令。
 *
 * 刻意每轮都注入(和 contPre / memory preamble 一致),而不是每会话一次:resume 不可靠的 provider 会静默
 * 丢掉早先的上下文,一次性注入等于开一轮就失效。这段指令本身约 600 token,相对它省下的阅读成本可以接受。
 */
export function inlineHtmlPreamble(enabled: boolean): string {
  return enabled ? INLINE_HTML_DIRECTIVE : ''
}
