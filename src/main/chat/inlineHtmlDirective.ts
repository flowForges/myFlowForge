//
// 纯 Markdown 是单列垂直流,表达对比矩阵、流程结构、密集信息卡片时只能靠不断换行和堆标题,回复越写越长
// 越难扫读。打开开关后把这段指令前置到每轮 prompt,鼓励模型在合适的场景改用内嵌 HTML 片段表达。
//
// 相对业界流传的那版提示词做了三处改动:
//   1) 删掉了允许输出 <script> 的措辞。渲染端的白名单本来就不会构造 script,但指令里留着它等于在教模型
//      写一段必然被丢弃的东西,白费 token,也让「模型输出」和「实际渲染」对不上。
//   2) 明确要求表格和代码块继续用 Markdown 原生语法。渲染端虽然会把 HTML 里的 <table>/<pre> 提升成应用
//      自己的组件(于是照样能排序/复制/折叠),但那条路对复杂表格会回退,不如从源头劝住。
//   3) 明确告诉模型配色会被接管,不必纠结具体色值 —— 它写死的十六进制会被映射到应用的主题 token,好让
//      卡片跟随皮肤和壁纸配色。省得它花 token 精心挑色。
