import { describe, expect, it } from 'vitest'
import { sessionKey } from './commandKey'

describe('sessionKey', () => {
  it.each([
    // 清单内的命令 + 子命令 → 两个词
    ['npm test', 'npm test'],
    ['npm test -- -t x', 'npm test'],
    ['  npm   test\t--watch ', 'npm test'],
    ['pnpm typecheck', 'pnpm typecheck'],
    ['yarn install', 'yarn install'],
    ['bun run build', 'bun run'],
    ['git status', 'git status'],
    ['git diff HEAD~1', 'git diff'],
    ['git rev-parse HEAD', 'git rev-parse'],
    ['cargo clippy', 'cargo clippy'],
    ['go vet ./...', 'go vet'],
    ['uv sync', 'uv sync'],
    ['pip list', 'pip list'],
    // 清单内的只读 / 构建命令 → 第一个词
    ['ls', 'ls'],
    ['ls src', 'ls'],
    ['cat ./a.txt', 'cat'],
    ['rg TODO src', 'rg'],
    ['make', 'make'],
    ['make build', 'make'],
    ['tsc', 'tsc'],
    ['tsc src/x.ts', 'tsc'],
    ['vitest run x', 'vitest'],
    ['pytest tests', 'pytest'],
    // 键保留原拼写:换个路径就是另一个键
    ['./node_modules/.bin/eslint src', './node_modules/.bin/eslint'],
    ['/usr/bin/git status', '/usr/bin/git status'],
  ])('%j → %j', (command, key) => {
    expect(sessionKey(command)).toBe(key)
  })

  it.each([
    // 拒绝规则:元字符、$、换行、空
    'npm test && rm -rf x',
    'npm test; rm -rf x',
    'npm test & sleep 1',
    'npm test | tee out',
    'echo `whoami`',
    'echo $(whoami)',
    'echo $HOME',
    'echo ${X}',
    'npm test > out.txt',
    'npm test < in.txt',
    'npm test\nrm -rf x',
    'npm test\r\nrm -rf x',
    '',
    '   ',
    // 拒绝规则:VAR= 前缀、第二个词以 - 开头、带引号
    'FOO=1 npm test',
    'ls -la',
    'tsc --noEmit',
    'git -c core.x=y status',
    'npm --prefix x test',
    'git "status"',
    "git 'push' --force",
    // 拒绝规则:第一个词拼写不朴素
    '"git" status',
    '\\git status',
    "g''it status",
    '(ls',
    '/bin/l? x',
    '~/bin/ls x',
    'C:\\Windows\\System32\\cmd.exe /c dir',
    // 清单外的子命令
    'git push',
    'git push --force',
    'git reset --hard',
    'git clean -fdx',
    'git config core.pager x',
    'npm publish',
    'npm exec rimraf ~',
    'npm x rimraf ~',
    'pnpm exec x',
    'pnpm dlx rimraf x',
    'yarn dlx x',
    'bun x rimraf',
    'uv run x.py',
    'uv tool x',
    'cargo install x',
    'go generate ./...',
    'pip uninstall x',
    'npm',
    'git',
    // 清单外的命令(前两轮评审提到的全部)
    'rm -rf build',
    'rm',
    'sudo npm test',
    'su root',
    'doas ls',
    'bash -c x',
    'sh x.sh',
    'zsh x',
    'pwsh x',
    'node 1x.js',
    'deno run x',
    'perl x',
    'python3 x.py',
    'python3.12 -c x',
    'pythonw x.py',
    'py x.py',
    'pypy3 x.py',
    'find . -delete',
    'xargs rm',
    'env npm test',
    'chmod 777 x',
    'dd if=x of=y',
    'mkfs /dev/sda',
    'mkfs.ext4 /dev/sda',
    'timeout 60 npm test',
    'nohup rm -rf build',
    'time npm test',
    'nice npm test',
    'ssh host ls',
    '. ./x.sh',
    'source x.sh',
    'watch npm test',
    'caffeinate npm test',
    'command rm x',
    'builtin cd x',
    'stdbuf npm test',
    'script out.txt',
    'pkexec /bin/sh',
    'runuser x',
    'sg x',
    'arch /bin/rm',
    'setsid rm x',
    'coproc rm x',
    'flock x rm',
    'chrt 1 x',
    'taskset 1 x',
    'ionice x',
    'unbuffer x',
    'sandbox-exec x',
    'osascript x',
    'npx rimraf build',
    'bunx rimraf',
    'uvx x',
    'pnpx x',
    'bundle exec x',
    'poetry run x',
    'pipx run x',
    'docker run img',
    'docker exec c sh',
    'kubectl exec p sh',
    'mv ./a b',
    'curl http://x',
    'kill 1',
    'cp a b',
    'touch x',
  ])('%j → undefined', command => {
    expect(sessionKey(command)).toBeUndefined()
  })

  it('a key never covers another subcommand or launcher', () => {
    expect(sessionKey('git push')).not.toBe(sessionKey('git status'))
    expect(sessionKey('npm exec rimraf ~')).not.toBe(sessionKey('npm test'))
  })
})
