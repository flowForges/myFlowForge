/**
 * 主机详情页上那行令牌的遮罩(`app/host.tsx`)。
 *
 * ★为什么**一个原字符都不露**(不是常见的「只露后 4 位」):这里的令牌是 bearer ——
 *  拿到它就等于拿到那台电脑上 agent 和终端的控制权(设置页自己写着「等于整台机器的控制权」)。
 *  「后 4 位」那种写法是给信用卡号设计的:卡号本身不是凭据,而且要靠尾号认出是哪一张。
 *  这里认哪一台主机靠的是主机名和地址,不靠令牌 —— 露出来的每一位都是净损失。
 *
 * ★为什么长度封顶:遮罩的长度会**泄露真实长度**(暴力破解时那是免费的一格信息),
 *  而且一个 64 位的令牌在 390pt 的屏上会把这一行撑到换行三次。封顶之后既不泄露长度,
 *  也画得下 —— 代价是看不出「我填的是长的那一个还是短的那一个」,而这件事本来就该靠
 *  「显示」按钮当场看真值,不该靠数点。
 *
 * ★不 import 任何 react-native,能在 node 那套 vitest 项目里直接测。
 */
export function maskToken(token: string): string {
  // 空 = 这台主机压根不要令牌(绑回环的 daemon)。返回空串,由界面去说那句话 ——
  // 在这儿返回「(没有令牌)」之类的中文会让这个函数同时管遮罩和文案,换文案就得改测试。
  if (!token) return ''
  return '•'.repeat(Math.min(token.length, 24))
}
