import { TREE } from './tree'

/**
 * 首页「全出血列表」的横向几何。
 *
 * ★为什么会有这个文件:真机上用户说「总感觉 app 是一个网页的感觉」,并自己定位到了根因 ——
 *  「顶部有顶栏,底部又是空的,工作区列表外包括顶栏是一样的颜色,而工作区是明显的白色,
 *   显得这是一个页面」。核实下来是字面事实:页面底 `bg` #f5f7f9、卡片 `surface` #ffffff,
 *  再加 `paddingHorizontal: 12` + `borderRadius: 13` —— 屏幕上就是**一块带圆角的白板浮在灰框里**,
 *  这是 web 的 chrome/content 分层语言,不是 app 的。
 *
 *  对照物是微信的会话列表:行贴着屏幕左右边缘,没有边距没有圆角,行的白就是这一屏的白,
 *  灰底只在列表真的走完之后才露出来。列表填满整屏 → 底部没有「空的」这回事。
 *
 * ★这里只放**横向**的量。★★纵向的量一律不准从这儿来 —— 首页的定位气泡靠三段 onLayout
 *  的 y 相加定位,任何纵向 margin 都会把那三段拆散,而且**一条测试都不会红**
 *  (布局在 node/jsdom 里量不了)。`minRowH` 是**最小高度**不是 margin:它算在本层高度里、
 *  不改本层自己的 y,所以是安全的。
 *
 * ★零 RN import(只 import 同样零依赖的 tree.ts),这样它能在 node 那套 vitest 里被直接测。
 */
export const HOME = {
  /** 一级(工作区)行的左右内边距。iOS 列表的标准值。 */
  rowInsetX: 16,
  /** 工作区行的最小高度。34pt 的色块 + 上下各 12 = 58。 */
  minRowH: 58,
  /** 会话行的最小高度。比工作区行矮一档,让层级在纵向上也读得出来。 */
  minDeepRowH: 54,
} as const

/**
 * 一条分隔线该从左边多少 pt 处开始。
 *
 * ★★**这是全出血列表表达层级的主要手段**,不是装饰。行没有边距也没有圆角之后,
 *  「这几条从属于上面那一行」只剩两件事在说:内容的缩进,和**分隔线的起点**。
 *  两条线都从 0 开始的话,工作区行和会话行会读成一列平级的东西。
 *
 * ★★`'session'` 这一档的分隔线,实现上**必须绝对定位在会话行内容区的底部**
 *  (`position:'absolute', left:0, right:0, bottom:0`,画在那个左沿已经是 44 的内容区里),
 *  **不能**当兄弟节点插在两行之间。插在中间的话,那 0.5pt 的高度会在主干上每行切一个口子 ——
 *  一列扫下来主干看着像一条画坏了的虚线。绝对定位零布局影响,主干保持连续。
 */
export function separatorInset(level: 'ws' | 'session'): number {
  return level === 'ws' ? HOME.rowInsetX : TREE.col
}
