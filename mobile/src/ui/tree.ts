/**
 * 工作区抽屉里那棵**树**的几何。
 *
 * ★为什么会有这个文件:真机上用户对着展开后的会话列表说
 *  「这是一根竖线,应该跟会话有连线,现在太low了」。
 *  原来那条线是照电脑端左侧栏抄的 `.ws-sess-list { border-left: 1px }` —— 一条画在**容器**上的
 *  竖线。它只说了「这几条是一伙的」,没说「**每一条**从属于上面那一行」,而且没有终点:
 *  一路划到抽屉底,末尾悬着,谁也不知道它指的是最后那张卡还是底下那颗按钮。
 *  改成真的树:每一条会话一个 `├─`,**最后一条** `└─` 把主干收住。
 *
 * ★为什么几何要单拎出来:**行高在这套代码里量不到,而且不许去量**
 *  (node/jsdom 测不了布局;Fabric 下的原生测量 API 这个环境没法验证 —— 见 `app/index.tsx`
 *  的 `absY()` 注释)。所以树是「**定宽的连接列** + 列内**绝对定位**」画出来的:
 *  主干在列内一个固定的 x,横杠挂在 `50%` 处 —— 全程不需要知道任何一行有多高。
 *  这几个数之间是有约束的(横杠不能长过连接列、得给卡片留一个气口、算出负数就完了),
 *  把数和约束放在一起才测得住。
 *
 * ★这个文件刻意**不 import 任何东西**(同 `wsTile.ts` / `sessionStatus.ts` / `listContinue.ts`):
 *  根 vitest.config.ts 里 `mobile` 那个 project 跑在 node 上,带 React Native 的东西在那儿
 *  import 不动,所以能离开 RN 的逻辑一律离开。
 */

export type TreeGeom = {
  /** 连接列的宽度。会话卡的左沿就落在这儿 —— 树画在卡片**外面**,不占卡片自己的内边距。 */
  col: number
  /** 主干在连接列里的 x。★全出血下连接列自己就贴着屏幕左沿,所以这个数就是主干的**绝对**位置。 */
  trunk: number
  /** 线宽。1 而不是 hairline:hairline 在高密度屏上是 0.33px,细到这棵树看着像没画。 */
  line: number
  /**
   * 横杠和卡片左沿之间的气口。贴着画的话横杠像是从卡片边框里长出来的。
   * ★屏幕上量到的空隙是 `gap + line`(浏览器实测 5px):横杠是**从主干那一格起**画的
   *  —— 多压那一格是为了把拐角那个像素填上,不然 `└` 的转角会缺一个点。
   */
  gap: number
}

/**
 * ★2026-08-28 全出血改造:col 22→44、trunk 7→26、rowGap 删除。
 *
 * 旧值属于「卡片式」时代:抽屉有 `marginHorizontal: 12`、`<List>` 又有 `marginLeft: 10`,
 * 于是主干的**绝对**位置是 10 + 7 = 17 —— 刻意对齐电脑端侧栏的那条 `border-left`。
 * 全出血之后那两段边距都没了(行直接贴屏幕左沿),主干必须自己站到 iOS 的二级缩进上:
 * 内容左沿 44、主干 26。
 *
 * ★★`rowGap` 删掉了,连同 `TreeGap` 那个组件。它原本是用来补上「两张会话卡之间那道缝里
 *  断掉的一小段主干」的。全出血之后行是**齐平**的,每一行的连接列 `top:0 → bottom:0`
 *  首尾相接 —— 主干天然连续,补丁没有存在理由了。
 *
 * ★44 同时是**会话行内容区的左沿**,也就是那条分隔线的起点(见 homeGeom.ts 的
 *  `separatorInset`)。两者必须相等,否则分隔线的起点和会话标题的左沿差一截 ——
 *  那是「一眼说不上哪儿不对」的典型来源。homeGeom.test.ts 钉住了这条跨文件约束。
 */
export const TREE: TreeGeom = { col: 44, trunk: 26, line: 1, gap: 4 }

/**
 * 横杠的长度:从主干右侧画到卡片左沿前那个气口。
 *
 * ★`Math.max(0, …)` 不是防御性废话:连接列被调窄到放不下的时候,这里会算出**负数**,
 *  而负宽度在 RN 上是未定义行为(不同平台表现不一样,不会有任何报错)。宁可退成
 *  「没有横杠」这个看得见的降级,也不要一个每个平台各错各的值。
 */
export function elbowWidth(t: TreeGeom = TREE): number {
  return Math.max(0, t.col - t.trunk - t.line - t.gap)
}

/**
 * 主干在第 `index` 行是**穿过去**还是**到中点为止**。
 *
 * ★`>=` 而不是 `===`:越界的下标(总数变了而调用方还拿着旧下标)也判成收住。
 *  判成穿过去的话,屏幕上那条主干会从最后一张卡底下**继续往下伸**,指着一颗
 *  根本不在树上的按钮 —— 那正是这次要改掉的毛病。
 */
export function trunkAt(index: number, total: number): 'through' | 'stop' {
  return index >= total - 1 ? 'stop' : 'through'
}

/**
 * 抽屉里一样东西的左缩进。
 *
 * ★**会话行是 0**:它自己头上就顶着连接列,缩进由那一列负责。
 *  其余几样(空态那句话、「＋ 新建会话」、建失败那句红字)不在树上,得手动缩到卡片左沿,
 *  否则它们会比上面几张卡凸出去一截,读起来像是从这个工作区里掉出来了。
 *
 * ★★为什么「＋ 新建会话」**不上树**(这次专门定的):
 *  树说的是「这几条**从属于**上面那个工作区」——它是一个包含关系,连的是**已经存在**的东西。
 *  而那一颗是**动作**(造一个还不存在的会话),它已经被刻意做成虚线透明底、就是为了和
 *  上面那几张实底的卡分开(见 index.tsx 那段注释)。把它接到树上等于把这个区分又抹掉。
 *  更硬的一条:主干由**最后一条会话**收住(`trunkAt`)。要是主干越过它继续伸到按钮上,
 *  那么收尾的 `└─` 就落在一个动作上 —— 等于说「这个工作区里的最后一样东西是一颗按钮」。
 *  两件事必须一致:**谁收住主干,主干就到谁为止**。
 */
export function indentFor(kind: 'session' | 'aside', t: TreeGeom = TREE): number {
  return kind === 'session' ? 0 : t.col
}
